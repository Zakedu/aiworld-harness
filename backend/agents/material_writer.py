async def generate_material(
    chapter: dict,
    blueprint: dict,
    mixer: dict,
    provider: str = "claude",
    prev_chapter: dict | None = None,
) -> dict:
    fb = (mixer or {}).get("_user_feedback") or ""
    fb_block = f"\n[사용자 피드백 — 이번 재생성 시 반드시 반영]\n{fb}\n" if fb else ""
    ai_tool = (mixer or {}).get("target_ai_tool") or "ChatGPT"
    prev_block = ""
    if prev_chapter:
        prev_block = (
            "[직전 챕터 — 도입부 첫 줄 브릿지에서 이어받을 것]\n"
            f"챕터: {prev_chapter.get('chapter_id')} — {prev_chapter.get('chapter_name')}\n"
            f"프롬프트 기법: {prev_chapter.get('prompt_technique','')}\n\n"
        )

    # 검증된 위인 어록 (blueprint.real_quotes) — 챕터마다 *다른* 어록 선택
    rq_list = blueprint.get("real_quotes") or []
    rq_block = ""
    if not rq_list:
        rq_block = (
            "[검증된 위인 어록 — blueprint에 real_quotes가 없음]\n"
            "  핵심 요약 마지막의 *위인 한마디 줄을 완전히 생략*하라.\n"
            "  LLM이 임의 생성한 어록 절대 금지. 따옴표 안 위인 발언 인용 0건.\n\n"
        )
    if rq_list:
        ch_id = chapter.get("chapter_id", "1-1")
        try:
            part_n, order_n = [int(x) for x in ch_id.split("-")[:2]]
            chapter_order = (part_n - 1) * 2 + (order_n - 1)  # 0~9
        except Exception:
            chapter_order = 0
        primary_idx = chapter_order % len(rq_list)
        primary = rq_list[primary_idx]
        others = [q for i, q in enumerate(rq_list) if i != primary_idx]
        rq_lines = "  주 어록 (이 챕터에 우선 사용):\n"
        rq_lines += f"    - \"{primary.get('text','')}\" — {primary.get('source','')} ({primary.get('source_url','')})\n"
        rq_lines += f"      맥락: {primary.get('context','')}\n"
        if others:
            rq_lines += "  대체 후보 (위 어록이 챕터 기법과 부합하지 않을 때만 선택):\n"
            for q in others[:3]:
                rq_lines += f"    - \"{q.get('text','')}\" — {q.get('source','')}\n"
        rq_block = (
            "[검증된 위인 어록 — 챕터마다 *다른* 어록 사용]\n"
            f"{rq_lines}"
            "  핵심 요약 마지막의 위인 한마디는 *주 어록*을 글자 그대로 사용 (또는 챕터 기법에 더 맞으면 대체 후보 중 1개).\n"
            "  변형·LLM 생성·번역 변경 금지. blueprint.real_quotes에 없는 어록 절대 사용 X.\n"
            "  같은 위인이라도 챕터마다 *다른* 어록 — 모든 챕터에서 동일 어록 반복 금지.\n\n"
        )

    # 위인 시그니처 워크플로우 — blueprint에서 받아 user prompt로 주입 (LLM 자체 생성 금지)
    sw = blueprint.get("signature_workflow") or {}
    sw_block = ""
    if sw and sw.get("steps"):
        sw_name = sw.get("name") or ""
        sw_steps = sw.get("steps") or []
        sw_rationale = sw.get("rationale") or ""
        sw_arrow = "→".join(sw_steps)
        sw_block = (
            "[위인 시그니처 워크플로우 — 글자 그대로 본문에 등장시킬 것]\n"
            f"  name: {sw_name}\n"
            f"  steps: {sw_steps} ({sw_arrow})\n"
            f"  rationale: {sw_rationale}\n"
            f"  [원리] 블록에 *위 name과 화살표 형태(\"{sw_name} — {sw_arrow}\")가 글자 그대로* 등장해야 한다.\n"
            f"  핵심 요약·체크리스트에도 동일 표현을 *그대로* 재등장시켜라 (변형 X).\n"
            f"  새로운 워크플로우 이름·단계를 만들지 마라. blueprint 정의가 *유일한 출처*다.\n\n"
        )

    # 직무 다양화 — 주력 직무 + 인접 2종
    persona = blueprint.get("learner_persona") or "(미정)"
    adj_jobs = blueprint.get("adjacent_jobs") or []
    adj_lines = []
    for i, j in enumerate(adj_jobs[:2]):
        label = (j or {}).get("job_label") or "(미정)"
        ctx = (j or {}).get("job_context") or "(미정)"
        adj_lines.append(f"  - 시나리오 {'B' if i == 0 else 'C'} 직무: {label} — {ctx}")
    job_block = (
        "[시나리오 직무 다양화 — 실전 적용 시나리오 섹션에 정확히 반영]\n"
        f"  - 시나리오 A 직무(주력): {persona}\n"
        + "\n".join(adj_lines)
        + "\n  3개 시나리오 모두 다른 직무·다른 페인포인트로 작성. 같은 시나리오 반복 X.\n\n"
    )

    user = (
        f"[과정]\n코스명: {blueprint.get('course_name')}\n"
        f"위인: {blueprint.get('character_name')}\n\n"
        f"{rq_block}"
        f"{sw_block}"
        f"{job_block}"
        f"{prev_block}"
        f"[이번 챕터]\n"
        f"챕터: {chapter['chapter_id']} — {chapter['chapter_name']}\n"
        f"파트: {chapter['part_name']}\n"
        f"프롬프트 기법: {chapter['prompt_technique']}\n\n"
        f"[타깃 AI 도구] Good/Better/Best 프롬프트 예시와 실전 시나리오는 '{ai_tool}' 기준으로 작성\n"
        f"[결과값 조절]\n"
        f"위인 활용 강도: {mixer.get('figure_voice','중간')} — "
        f"{'약(이름 등장 하한선 6회, 일화 가볍게)' if mixer.get('figure_voice')=='약' else '강(이름 등장 12회+, 일화·인용 풍부)' if mixer.get('figure_voice')=='강' else '중간(이름 10회+, 표준)'}\n"
        f"{fb_block}\n"
        "위 조건으로 학습자료 본문을 위 출력 JSON 구조로 반환하라."
    )
    sys = resolve_prompt("material_writer", SYSTEM_PROMPT)
    content = await call_model(provider, sys, user, json_mode=True, temperature=0.6, max_tokens=8000)  # type: ignore
    return _ensure_kinds(content)


def _ensure_kinds(content: dict) -> dict:
    """LLM이 sections[].kind 필드를 누락하는 패턴 대응 — heading 기반으로 자동 보정."""
    if not isinstance(content, dict):
        return content
    sections = content.get("sections")
    if not isinstance(sections, list):
        return content
    for s in sections:
        if not isinstance(s, dict):
            continue
        if s.get("kind"):
            continue
        heading = (s.get("heading") or "").strip()
        body = (s.get("body") or "")[:200]
        if "원리" in heading or "핵심 개념" in heading:
            s["kind"] = "concept"
        elif "더 좋은 프롬프트" in heading or "프롬프트 만들기" in heading or "Bad" in body:
            s["kind"] = "example"
        elif "시나리오" in heading:
            s["kind"] = "template"
        elif "체크리스트" in heading or "요약" in heading or "정리" in heading:
            s["kind"] = "reflection"
        else:
            idx = sections.index(s)
            s["kind"] = ["concept", "example", "template", "reflection", "reflection"][min(idx, 4)]
    return content
