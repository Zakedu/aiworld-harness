async def generate_story(
    chapter: dict,
    blueprint: dict,
    mixer: dict,
    provider: str = "claude",
    prev_chapter: dict | None = None,
) -> dict:
    fb = (mixer or {}).get("_user_feedback") or ""
    fb_block = f"\n[사용자 피드백 — 이번 재생성 시 반드시 반영]\n{fb}\n" if fb else ""
    prev_block = ""
    if prev_chapter:
        prev_img = prev_chapter.get('image_prompt', '') or ''
        img_avoid = ""
        if prev_img:
            img_avoid = (
                "[직전 챕터 image_prompt — 이번 image_prompt는 *서로 다른 장면*으로 작성]\n"
                f"  {prev_img[:300]}\n"
                "  장소·인물 자세·시간대 중 *최소 2개*는 위와 달라야 함 (동일 장면 반복 금지).\n\n"
            )
        prev_block = (
            "[직전 챕터 — 도입 한 줄에서 이어받을 것]\n"
            f"챕터: {prev_chapter.get('chapter_id')} — {prev_chapter.get('chapter_name')}\n"
            f"프롬프트 기법: {prev_chapter.get('prompt_technique','')}\n\n"
            f"{img_avoid}"
        )

    # 챕터 진도 (1-1 → 5-2 점진 가이드용)
    cid = chapter.get("chapter_id", "1-1")
    try:
        part_n, order_n = [int(x) for x in cid.split("-")[:2]]
    except Exception:
        part_n, order_n = 1, 1
    if part_n == 1:
        prog_zone = "1파트 (입문)"
        prog_guide = "위인의 *처음 시도한 작은 사례*·1~2단계 단순 행동. 학습자 '처음 부딪힌 막막함' 환기. 단일 기법 도입."
    elif part_n in (2, 3):
        prog_zone = f"{part_n}파트 (응용)"
        prog_guide = "위인의 *대표 성과·잘 알려진 일화*·3~4단계 구조. 학습자 '기법 일부 익혔지만 응용 막힘'. 기법 복합."
    elif part_n == 4:
        prog_zone = "4파트 (심화)"
        prog_guide = "위인의 *핵심 업적·가장 깊은 통찰·전환점*. 학습자 '고급 의사결정 상황'. 다중 기법 결합."
    else:
        # 5파트 — blueprint.final_part_pattern에 맞춰 종말 톤 결정
        fpp = (blueprint.get("final_part_pattern") or {})
        fpp_id = fpp.get("id") or "integration"
        prog_zone = f"5파트 ({fpp.get('label') or '종합'})"
        if fpp_id == "library":
            prog_guide = "위인 워크플로우를 *템플릿·자산*으로 굳히는 장면. 학습자 '다음 일에 바로 쓸 라이브러리 완성'. 학습 약속: '~을 라이브러리로 정리해 다음 일에 즉시 활용합니다' 톤."
        elif fpp_id == "simulation":
            prog_guide = "위인의 *실전 적용·외부 평가* 장면. 학습자 '실제 조건에서 검증'. 학습 약속: '~을 실전 조건에서 적용·점검합니다' 톤."
        elif fpp_id == "extension":
            prog_guide = "위인의 *다음 도약·외부 결합* 장면. 학습자 '코스 너머 응용'. 학습 약속: '~을 다음 단계 도구·맥락에 결합해 확장합니다' 톤."
        elif fpp_id == "retrospective":
            prog_guide = "위인의 *학습 방법론 점검* 장면. 학습자 '학습법 자체 정착'. 학습 약속: '~의 학습 방법론을 자기 일에 정착합니다' 톤. (단, 학습법·메타학습 코스에만 적합)"
        else:  # integration (기본)
            prog_guide = "위인의 *결과물 통합·완성* 장면. 학습자 '1~4파트 산출물을 하나의 완성본으로 묶음'. 학습 약속: '~을 하나의 통합 결과물로 완성합니다' 톤."
        prog_guide += f"\n  [코스 final_part_pattern.rationale] {fpp.get('rationale','')}"
    prog_block = (
        f"[챕터 진도 — 점진적 난이도 가이드]\n"
        f"이 챕터의 진도 위치: {cid} = {prog_zone}\n"
        f"  → {prog_guide}\n"
        f"  → 같은 위인이라도 이전 챕터와 *다른 일화·다른 시점* 선택 (동일 사건 반복 금지)\n\n"
    )

    user = (
        f"[과정]\n코스명: {blueprint.get('course_name')}\n"
        f"위인: {blueprint.get('character_name')}\n\n"
        f"{prog_block}"
        f"{prev_block}"
        f"[이번 챕터]\n"
        f"챕터: {chapter['chapter_id']} — {chapter['chapter_name']}\n"
        f"파트: {chapter['part_name']}\n"
        f"프롬프트 기법: {chapter['prompt_technique']}\n\n"
        f"[결과값 조절] 위인 활용 강도: {mixer.get('figure_voice','중간')}\n"
        f"{fb_block}\n"
        "위 조건으로 챕터 시작 페이지의 스토리·이미지 프롬프트를 위 출력 JSON 구조로 반환하라."
    )
    sys = resolve_prompt("story_writer", SYSTEM_PROMPT)
